REASON_CODES: dict[str, ReasonCodeSpec] = {spec.code: spec for spec in _SPECS}


def compute_verdict(codes: list[str]) -> Verdict:
    """Computes final verdict using strict precedence ERROR > FAIL > NO VERDICT > PASS."""
    if not codes:
        return Verdict.NO_VERDICT
    highest = Verdict.PASS
    for code in codes:
        spec = REASON_CODES.get(code)
        verdict = spec.verdict if spec is not None else Verdict.ERROR
        if VERDICT_PRECEDENCE[verdict] > VERDICT_PRECEDENCE[highest]:
            highest = verdict
    return highest


def explain_reason_code(code: str) -> ReasonCodeSpec | None:
    """Returns metadata for a stable machine-readable reason code."""
    return REASON_CODES.get(code.strip())
